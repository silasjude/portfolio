let select = document.querySelector('.color-scheme select');

function setColorScheme(colorScheme) {
  document.documentElement.style.setProperty('color-scheme', colorScheme);
  select.value = colorScheme;
}

if ('colorScheme' in localStorage) {
  setColorScheme(localStorage.colorScheme);
}

select.addEventListener('input', function (event) {
  console.log('color scheme changed to', event.target.value);
  setColorScheme(event.target.value);
  localStorage.colorScheme = event.target.value;
});

let form = document.querySelector('form');

form?.addEventListener('submit', function (event) {
  event.preventDefault();

  let data = new FormData(form);
  let params = [];

  for (let [name, value] of data) {
    params.push(name + '=' + encodeURIComponent(value));
  }

  let url = form.action + '?' + params.join('&');
  location.href = url;
});

export async function fetchJSON(url) {
  try {
    // Fetch the JSON file from the given URL
    const response = await fetch(url);
    if (!response.ok) {
      throw new Error(`Failed to fetch projects: ${response.statusText}`);
    }
    const data = await response.json();
    return data;
  } catch (error) {
    console.error('Error fetching or parsing JSON data:', error);
  }
}

export function renderProjects(project, containerElement, headingLevel = 'h2') {
  // Make sure the container exists before rendering
  if (!containerElement) {
    console.error('renderProjects: containerElement not found');
    return;
  }

  // Only allow valid heading tags, otherwise fall back to h2
  if (!/^h[1-6]$/.test(headingLevel)) {
    console.warn(`Invalid heading level "${headingLevel}", using h2 instead`);
    headingLevel = 'h2';
  }

  containerElement.innerHTML = '';

  // Accept either a single project or an array of projects
  const projects = Array.isArray(project) ? project : [project];

  for (let p of projects) {
    // Local image paths are relative to the site root, so they work from any page
    const imageSrc = p.image.startsWith('http') ? p.image : BASE_PATH + p.image;

    const article = document.createElement('article');
    article.innerHTML = `
      <${headingLevel}>${p.title}</${headingLevel}>
      <img src="${imageSrc}" alt="${p.title}">
      <p>${p.description}</p>
    `;
    containerElement.appendChild(article);
  }
}

